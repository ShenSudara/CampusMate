import Foundation

// Current weather at a destination, reduced to what fits on one line.
struct DestinationWeather: Equatable {
    let temperature: Double
    let weatherCode: Int
    let isDay: Bool

    var temperatureText: String { "\(Int(temperature.rounded()))°" }

    // Groups the WMO weather codes used by Open-Meteo into short descriptions.
    var summary: String {
        switch weatherCode {
        case 0: return "Clear"
        case 1, 2: return "Partly cloudy"
        case 3: return "Cloudy"
        case 45, 48: return "Fog"
        case 51...57: return "Drizzle"
        case 61...67, 80...82: return "Rain"
        case 71...77, 85, 86: return "Snow"
        case 95...99: return "Thunderstorm"
        default: return "Unknown"
        }
    }

    var systemImage: String {
        switch weatherCode {
        case 0: return isDay ? "sun.max.fill" : "moon.stars.fill"
        case 1, 2: return isDay ? "cloud.sun.fill" : "cloud.moon.fill"
        case 3: return "cloud.fill"
        case 45, 48: return "cloud.fog.fill"
        case 51...57: return "cloud.drizzle.fill"
        case 61...67, 80...82: return "cloud.rain.fill"
        case 71...77, 85, 86: return "cloud.snow.fill"
        case 95...99: return "cloud.bolt.rain.fill"
        default: return "cloud.fill"
        }
    }
}
